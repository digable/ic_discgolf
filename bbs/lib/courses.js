// Copies of holes with their lengths (ft) set, one per length
function holesWithFt(holes, ft) {
	var out = [];
	for (var i = 0; i < ft.length; i++) {
		var h = {}, k;
		for (k in holes[i]) h[k] = holes[i][k];
		h.ft = ft[i];
		out.push(h);
	}
	return out;
}

